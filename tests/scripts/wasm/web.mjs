#!/usr/bin/env node
/**
 * The web app's copy of the WebAssembly core (docs/RAIL-PLAN.md R4.1).
 *
 *   npm run wasm:web          build `--target web`, copy it into the web app
 *   npm run wasm:web-check    compare a fresh `pkg/web` build with the copy
 *
 * Vercel builds `frontend/` and has no Rust, so the wasm-bindgen output the
 * web runs is committed at {@link OUT} (`.wasm`, JS glue, declarations) with
 * a `BUILD.json` naming the toolchain and every file's sha-256. The build is
 * a pure function of the sources, `rust-toolchain.toml`, Cargo.lock and the
 * pinned wasm-bindgen-cli (`build.mjs` takes this machine's paths out of the
 * module), so CI rebuilds it and fails when the committed copy differs - a
 * Rust change that forgot `npm run wasm:web`, or a hand edit. The same idea
 * as `golden-fresh`.
 *
 * `--check` reads `core/rail-core-wasm/pkg/web/` (run `npm run wasm:build --
 * web` first; CI's `wasm` job does) and writes nothing.
 */

import { createHash } from "node:crypto";
import { spawnSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";
import { gzipSync } from "node:zlib";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "../../..");
const PKG = join(ROOT, "core/rail-core-wasm/pkg/web");
export const OUT = join(ROOT, "frontend/src/lib/wasm/rail-core");

/** What wasm-bindgen writes for `--target web`, all of it shipped. */
export const FILES = ["rail_core_wasm.js", "rail_core_wasm.d.ts", "rail_core_wasm_bg.wasm", "rail_core_wasm_bg.wasm.d.ts"];

function sha256(bytes) {
  return createHash("sha256").update(bytes).digest("hex");
}

function rustc() {
  const result = spawnSync("rustc", ["-V"], { cwd: ROOT, encoding: "utf8" });
  if (result.error || result.status !== 0) {
    throw new Error("wasm:web: `rustc -V` failed");
  }
  return result.stdout.trim();
}

function lockedBindgenVersion() {
  const lock = readFileSync(join(ROOT, "Cargo.lock"), "utf8").replace(/\r\n/g, "\n");
  return /\[\[package\]\]\nname = "wasm-bindgen"\nversion = "([^"]+)"/.exec(lock)?.[1] ?? null;
}

/** The files as they should be committed: the build's four plus `BUILD.json`. */
function expected() {
  const missing = FILES.filter((name) => !existsSync(join(PKG, name)));
  if (missing.length > 0) {
    console.error(`wasm:web: ${relative(ROOT, PKG)} has no ${missing.join(", ")}: run \`npm run wasm:build -- web\` first`);
    process.exit(1);
  }
  const files = new Map(FILES.map((name) => [name, readFileSync(join(PKG, name))]));
  const wasm = files.get("rail_core_wasm_bg.wasm");
  const build = {
    "//": "Generated by `npm run wasm:web` in tests/ (docs/RAIL-PLAN.md R4.1). Do not edit; CI rebuilds and compares.",
    rustc: rustc(),
    wasmBindgen: lockedBindgenVersion(),
    profile: "wasm-release",
    gzip: gzipSync(wasm, { level: 9 }).length,
    files: Object.fromEntries(FILES.map((name) => [name, { bytes: files.get(name).length, sha256: sha256(files.get(name)) }])),
  };
  files.set("BUILD.json", Buffer.from(`${JSON.stringify(build, null, 2)}\n`));
  return files;
}

const check = process.argv.includes("--check");
const want = expected();

if (!check) {
  rmSync(OUT, { recursive: true, force: true });
  mkdirSync(OUT, { recursive: true });
  for (const [name, bytes] of want) {
    writeFileSync(join(OUT, name), bytes);
  }
  const wasm = want.get("rail_core_wasm_bg.wasm");
  console.log(
    `wasm:web: ${relative(ROOT, OUT)}: rail_core_wasm_bg.wasm ${(wasm.length / 1e6).toFixed(2)} MB, sha-256 ${sha256(wasm).slice(0, 16)}...`,
  );
  process.exit(0);
}

const problems = [];
const committed = existsSync(OUT) ? readdirSync(OUT) : [];
for (const [name, bytes] of want) {
  const path = join(OUT, name);
  if (!existsSync(path)) {
    problems.push(`${name}: missing`);
    continue;
  }
  const have = readFileSync(path);
  if (!have.equals(bytes)) {
    problems.push(`${name}: committed sha-256 ${sha256(have).slice(0, 16)}..., fresh build ${sha256(bytes).slice(0, 16)}...`);
  }
}
for (const name of committed) {
  if (!want.has(name)) {
    problems.push(`${name}: not part of the build`);
  }
}
if (problems.length > 0) {
  console.error(
    `wasm:web: ${relative(ROOT, OUT)} is not what the sources build:\n  ${problems.join("\n  ")}\n` +
      "Run `npm run wasm:web` in tests/ and commit the directory (CI uploads its own build as the artefact `rail-core-web`).",
  );
  process.exit(1);
}
console.log(`wasm:web: ${relative(ROOT, OUT)} is what the sources build (${want.size} files).`);
