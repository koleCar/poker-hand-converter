/**
 * Writes the push/fold equity table (R5.5): the heads-up all-in equity of
 * each of the 169 hand classes against each other, with card removal -
 * `preflopEquityTable` of `lib/solver` (the chart generator's own table, our
 * own computation) at `PUSH_FOLD_EQUITY_BOARDS` boards - quantised to 16 bits
 * and committed as `frontend/src/lib/analysis/data/pushFoldEquity.ts`.
 *
 *     cd tests && npm run icm:equity
 *
 * Only the cells above the diagonal are stored: the table is symmetrised
 * (`E[i][j] + E[j][i] = 1`) and its diagonal is 0.5. The run prints the
 * standard error of an entry and the largest quantisation error, and checks
 * the decoded table against the computed one.
 */

import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { expect, it } from "vitest";

import { decodePushFoldEquity, encodePushFoldEquity, PUSH_FOLD_EQUITY_BOARDS, PUSH_FOLD_EQUITY_SEED } from "../../../frontend/src/lib/analysis/pushFold.js";
import { NUM_CLASSES, preflopEquityTable } from "../../../frontend/src/lib/solver/index.js";

const OUT = join(import.meta.dirname, "../../../frontend/src/lib/analysis/data/pushFoldEquity.ts");

it("writes the push/fold equity table", () => {
  const boards = Number(process.env.ICM_EQUITY_BOARDS ?? PUSH_FOLD_EQUITY_BOARDS);
  const t0 = performance.now();
  const table = preflopEquityTable({ boards, seed: PUSH_FOLD_EQUITY_SEED });
  const seconds = (performance.now() - t0) / 1000;
  const encoded = encodePushFoldEquity(table.equity);
  const text = [
    "/**",
    " * GENERATED by `tests/scripts/icm/equity.test.ts` (`npm run icm:equity`); do not edit.",
    " *",
    " * The heads-up all-in equity of each of the 169 hand classes against each",
    " * other, with card removal: `preflopEquityTable` (lib/solver) - Rail's own",
    ` * computation - over ${boards.toLocaleString("en-US")} seeded boards (seed 0x${PUSH_FOLD_EQUITY_SEED.toString(16)}), the cells above the`,
    " * diagonal as 16-bit fractions, base64 (`decodePushFoldEquity` in pushFold.ts).",
    ` * Standard error of an entry about ${table.standardError.toFixed(5)}.`,
    " */",
    `export const PUSH_FOLD_EQUITY_META = { boards: ${boards}, seed: ${PUSH_FOLD_EQUITY_SEED}, standardError: ${table.standardError.toFixed(6)} } as const;`,
    "",
    `export const PUSH_FOLD_EQUITY_DATA =\n  "${encoded}";`,
    "",
  ].join("\n");
  writeFileSync(OUT, text);
  // The committed table decodes to the computed one, to the quantum.
  const decoded = decodePushFoldEquity(encoded);
  let worst = 0;
  for (let k = 0; k < NUM_CLASSES * NUM_CLASSES; k += 1) worst = Math.max(worst, Math.abs(decoded[k] - table.equity[k]));
  console.log(`push/fold equity: ${boards} boards in ${seconds.toFixed(1)} s, standard error ${table.standardError.toFixed(5)}, quantisation ${worst.toExponential(2)}, ${encoded.length} chars`);
  expect(worst).toBeLessThan(1 / 65_535);
});
