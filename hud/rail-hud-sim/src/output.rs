//! The hand-history folder the simulator writes, and how a hand is
//! appended to a table's file.
//!
//! The folder is the simulator's own: a new one under the system's
//! temporary directory by default, or one given with `--out` that is empty
//! or was made by the simulator (it holds [`MARKER`]). Anything else is
//! refused, so a real client's folder is never written to.

use std::io::Write as _;
use std::path::{Path, PathBuf};

use crate::room::{FileEncoding, LineEnd};

/// The file that marks a folder as the simulator's (hidden: the watcher
/// skips it).
pub const MARKER: &str = ".rail-hud-sim";

/// A new folder under the system's temporary directory.
pub fn temp_out() -> PathBuf {
    std::env::temp_dir().join("rail-hud-sim").join(format!(
        "{}-{}",
        crate::clock::unix_ms(),
        std::process::id()
    ))
}

/// Make `dir` ready to write into, or say why it is not the simulator's.
pub fn prepare(dir: &Path) -> Result<(), String> {
    if dir.components().any(|c| {
        let c = c.as_os_str().to_string_lossy().to_lowercase();
        c == "handhistory" || c == "hand history" || c == "hands"
    }) {
        return Err(format!(
            "{} looks like a poker client's hand-history folder; the simulator writes only to its own folders",
            dir.display()
        ));
    }
    if dir.exists() {
        let mut entries = std::fs::read_dir(dir).map_err(|e| format!("{}: {e}", dir.display()))?;
        let empty = entries.next().is_none();
        if !empty && !dir.join(MARKER).is_file() {
            return Err(format!(
                "{} is not empty and was not made by the simulator (no {MARKER} in it)",
                dir.display()
            ));
        }
    }
    std::fs::create_dir_all(dir).map_err(|e| format!("{}: {e}", dir.display()))?;
    std::fs::write(
        dir.join(MARKER),
        "Generated by rail-hud-sim (docs/RAIL-PLAN.md R3.1): fake tables replaying corpus hands. Safe to delete.\n",
    )
    .map_err(|e| format!("{}: {e}", dir.display()))
}

/// The bytes of one hand as the room appends it: line ends, the separator
/// after it, the encoding, and a byte-order mark when the file is new.
pub fn encode(
    text: &str,
    separator: u32,
    line_end: LineEnd,
    encoding: FileEncoding,
    new_file: bool,
) -> Vec<u8> {
    let eol = match line_end {
        LineEnd::Lf => "\n",
        LineEnd::Crlf => "\r\n",
    };
    let mut body = text.trim_end().replace('\n', eol);
    for _ in 0..separator.max(1) {
        body.push_str(eol);
    }
    match encoding {
        FileEncoding::Utf8 => body.into_bytes(),
        FileEncoding::Utf8Bom => {
            let mut out = Vec::with_capacity(body.len() + 3);
            if new_file {
                out.extend_from_slice(&[0xef, 0xbb, 0xbf]);
            }
            out.extend_from_slice(body.as_bytes());
            out
        }
        FileEncoding::Utf16Le => {
            let mut out = Vec::with_capacity(body.len() * 2 + 2);
            if new_file {
                out.extend_from_slice(&[0xff, 0xfe]);
            }
            for unit in body.encode_utf16() {
                out.extend_from_slice(&unit.to_le_bytes());
            }
            out
        }
    }
}

/// Append one hand to `path` in a single write, as a client does when a
/// hand ends. Returns the bytes written.
pub fn append(
    path: &Path,
    text: &str,
    separator: u32,
    line_end: LineEnd,
    encoding: FileEncoding,
) -> Result<usize, String> {
    let new_file = std::fs::metadata(path)
        .map(|m| m.len() == 0)
        .unwrap_or(true);
    let bytes = encode(text, separator, line_end, encoding, new_file);
    let mut file = std::fs::OpenOptions::new()
        .create(true)
        .append(true)
        .open(path)
        .map_err(|e| format!("{}: {e}", path.display()))?;
    file.write_all(&bytes)
        .and_then(|()| file.flush())
        .map_err(|e| format!("{}: {e}", path.display()))?;
    Ok(bytes.len())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn encodings() {
        assert_eq!(
            encode("a\nb\n", 3, LineEnd::Lf, FileEncoding::Utf8Bom, true),
            b"\xef\xbb\xbfa\nb\n\n\n"
        );
        assert_eq!(
            encode("a\nb", 2, LineEnd::Crlf, FileEncoding::Utf8Bom, false),
            b"a\r\nb\r\n\r\n"
        );
        assert_eq!(
            encode("a", 1, LineEnd::Lf, FileEncoding::Utf16Le, true),
            [0xff, 0xfe, b'a', 0, b'\n', 0]
        );
        assert_eq!(
            encode("a", 1, LineEnd::Lf, FileEncoding::Utf8, true),
            b"a\n"
        );
    }

    #[test]
    fn only_its_own_folders() {
        let base = std::env::temp_dir().join(format!("rail-hud-sim-test-{}", std::process::id()));
        let _ = std::fs::remove_dir_all(&base);
        let ours = base.join("ours");
        assert!(prepare(&ours).is_ok());
        assert!(prepare(&ours).is_ok(), "a second run into the same folder");
        let theirs = base.join("theirs");
        std::fs::create_dir_all(&theirs).expect("dir");
        std::fs::write(theirs.join("HH20260101 x.txt"), "x").expect("file");
        assert!(prepare(&theirs).is_err());
        assert!(prepare(&base.join("PokerStars").join("HandHistory").join("me")).is_err());
        let _ = std::fs::remove_dir_all(&base);
    }
}
