//! TypeScript declarations generated from the PHF model.
//!
//! The model's types derive `ts_rs::TS` in test builds only (ts-rs is a
//! dev-dependency, so nothing of it reaches the library or the WASM build).
//! `generated_declarations_are_fresh` renders them into one file,
//! `core/rail-core-wasm/types/phf.d.ts`, and fails when the checked-in file
//! differs; `RAIL_UPDATE_DTS=1 cargo test -p rail-core --lib phf::dts` rewrites
//! it. `npm run phf:dts-check` in `tests/` then holds the file to
//! `web/src/lib/phf/types.ts` type by type.
//!
//! ts-rs renders every `i64` as the configured "large int" type. `Amount` is
//! the only `i64` in the model, so the generator names it `Amount` and the file
//! declares `type Amount = number`, exactly as `types.ts` does.

use std::collections::BTreeSet;
use std::fmt::Write as _;
use std::path::PathBuf;

use ts_rs::{Config, TS, TypeVisitor};

use super::{
    ActionType, AnteModel, ChipMovementAnchor, CurrencyKind, CurrencyUnit, DecimalStyle,
    GameFormat, LimitType, PhfAction, PhfBoard, PhfBombPot, PhfBounty, PhfChipMovement, PhfFees,
    PhfGame, PhfHand, PhfMarkerLabels, PhfMeta, PhfPlayer, PhfPlayerResult, PhfPot, PhfResults,
    PhfRunout, PhfSchema, PhfStraddle, PhfTable, PhfTextStyle, PhfTournament, PhfWarning,
    PhfWinner, Position, PotHalf, SeatOutcome, Street, Variant,
};

/// Where the declarations live, relative to the workspace root. Not under
/// `pkg/`: that is wasm-pack's output directory, which it rewrites (and
/// gitignores) on every build.
const DTS_PATH: &str = "core/rail-core-wasm/types/phf.d.ts";

const HEADER: &str = "\
// GENERATED by rail-core from core/rail-core/src/phf/mod.rs - do not edit.
// Regenerate: RAIL_UPDATE_DTS=1 cargo test -p rail-core --lib phf::dts
// Compared with web/src/lib/phf/types.ts by `npm run phf:dts-check` in tests/.

/** Integer minor units (see CurrencyUnit). Every i64 in the Rust model is an Amount. */
export type Amount = number;
";

/// Appends `export type X = ...;` with its doc comment for each listed type, in
/// the order given (roughly the order of `types.ts`).
macro_rules! declarations {
    ($cfg:expr, $out:expr, $($ty:ty),+ $(,)?) => {{
        let mut names = BTreeSet::new();
        $(
            $out.push('\n');
            if let Some(docs) = <$ty as TS>::docs() {
                $out.push_str(&docs);
            }
            let _ = writeln!($out, "export {}", <$ty as TS>::decl($cfg));
            names.insert(<$ty as TS>::ident($cfg));
        )+
        names
    }};
}

fn config() -> Config {
    Config::new().with_large_int("Amount")
}

fn render() -> (String, BTreeSet<String>) {
    let cfg = config();
    let mut out = String::from(HEADER);
    let names = declarations!(
        &cfg,
        out,
        PhfSchema,
        CurrencyKind,
        CurrencyUnit,
        DecimalStyle,
        Street,
        Variant,
        LimitType,
        GameFormat,
        AnteModel,
        Position,
        PhfStraddle,
        PhfBombPot,
        PhfGame,
        PhfTable,
        PhfBounty,
        PhfTournament,
        PhfPlayer,
        ActionType,
        PotHalf,
        PhfAction,
        PhfMarkerLabels,
        PhfRunout,
        PhfBoard,
        ChipMovementAnchor,
        PhfChipMovement,
        PhfFees,
        SeatOutcome,
        PhfPlayerResult,
        PhfPot,
        PhfWinner,
        PhfResults,
        PhfWarning,
        PhfTextStyle,
        PhfMeta,
        PhfHand,
    );
    // ts-rs leaves a space after `{` and `,` where a doc comment follows.
    let mut tidy = String::with_capacity(out.len());
    for line in out.lines() {
        tidy.push_str(line.trim_end());
        tidy.push('\n');
    }
    (tidy, names)
}

/// Every named type reachable from `PhfHand`, by its TypeScript name.
fn reachable_from_hand() -> BTreeSet<String> {
    struct Collect<'a> {
        cfg: &'a Config,
        seen: BTreeSet<String>,
    }
    impl TypeVisitor for Collect<'_> {
        fn visit<T: TS + 'static + ?Sized>(&mut self) {
            if T::output_path().is_some() && self.seen.insert(T::ident(self.cfg)) {
                T::visit_dependencies(self);
            }
        }
    }
    let cfg = config();
    let mut collect = Collect {
        cfg: &cfg,
        seen: BTreeSet::new(),
    };
    collect.visit::<PhfHand>();
    collect.seen
}

fn dts_path() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .join("../..")
        .join(DTS_PATH)
}

#[test]
fn every_reachable_type_is_declared() {
    let (_, declared) = render();
    assert_eq!(declared, reachable_from_hand());
}

#[test]
fn no_bigint_in_declarations() {
    let (text, _) = render();
    assert!(
        !text.contains("bigint"),
        "a 64-bit integer reached the declarations without being an Amount"
    );
}

#[test]
fn generated_declarations_are_fresh() {
    let (text, _) = render();
    let path = dts_path();
    if std::env::var_os("RAIL_UPDATE_DTS").is_some() {
        if let Some(dir) = path.parent() {
            std::fs::create_dir_all(dir).expect("create the declarations directory");
        }
        std::fs::write(&path, &text).expect("write the declarations");
        return;
    }
    let on_disk = std::fs::read_to_string(&path).unwrap_or_default();
    assert!(
        on_disk == text,
        "{DTS_PATH} is stale (or missing). The PHF model changed; regenerate it with\n\
         \n    RAIL_UPDATE_DTS=1 cargo test -p rail-core --lib phf::dts\n\n\
         and commit the result. Then run `npm run phf:dts-check` in tests/ to compare it \
         with web/src/lib/phf/types.ts."
    );
}
